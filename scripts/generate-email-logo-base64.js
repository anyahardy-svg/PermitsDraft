#!/usr/bin/env node

const fs = require('fs');
const path = require('path');

const assetsDir = path.join(__dirname, '..', 'public', 'email-assets');
const manifestPath = path.join(assetsDir, 'manifest.json');
const outputPath = path.join(__dirname, '..', 'api', 'lib', 'emailLogoBase64.js');

function generateEmailLogoBase64Module() {
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const entries = manifest.map(({ file, width, height }) => {
    const buffer = fs.readFileSync(path.join(assetsDir, file));
    const base64 = buffer.toString('base64');
    return { file, width, height, dataUri: `data:image/jpeg;base64,${base64}` };
  });

  const lines = [
    '// Auto-generated by scripts/generate-email-logo-base64.js — do not edit manually.',
    'module.exports = {',
    ...entries.map(
      (entry) => `  ${JSON.stringify(entry.file)}: { width: ${entry.width}, height: ${entry.height}, dataUri: ${JSON.stringify(entry.dataUri)} },`
    ),
    '};',
    '',
  ];

  fs.writeFileSync(outputPath, lines.join('\n'));
  console.log(`Generated ${outputPath} (${entries.length} logos)`);
}

if (require.main === module) {
  generateEmailLogoBase64Module();
}

module.exports = { generateEmailLogoBase64Module };
